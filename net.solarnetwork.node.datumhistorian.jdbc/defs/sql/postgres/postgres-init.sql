/* ============================================================================
 * SQL script to create the tables and functions used by the JDBC
 * DatumHistorian. Requires Postgres 17 or later, built with ICU support.
 *
 * Run this as the database role SolarNode connects with, or as a role that
 * role is a member of: solarhist.dh_store_datum() adds partitions to the
 * solarhist.dh_datum table as needed.
 *
 * Set jit = off for the historian database or role, as JIT compilation can
 * take longer than the historian's queries themselves, such as the reading
 * difference queries of solarhist.dh_find_datum_diff_rows():
 *
 *     ALTER DATABASE solarnode SET jit = off;
 * ============================================================================
 */

CREATE SCHEMA IF NOT EXISTS solarhist;

-- natural sort order, so source ID "a2" sorts before "a10"; the same as the SolarNet
-- solarcommon.naturalsort collation
CREATE COLLATION IF NOT EXISTS solarhist.naturalsort (provider = icu, locale = 'und-u-kf-upper-kn');

-- datum type registry: one row per datum class that has been stored
CREATE TABLE solarhist.dh_datum_type (
	type_id		SMALLINT GENERATED BY DEFAULT AS IDENTITY,
	created		TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	class_name	TEXT NOT NULL,				-- datum class name
	type_names	TEXT[] NOT NULL,			-- names of all classes/interfaces the class can be assigned to
	CONSTRAINT dh_datum_type_pk PRIMARY KEY (type_id),
	CONSTRAINT dh_datum_type_unq UNIQUE (class_name)
);

-- datum stream registry: one row per node + source (+ location) that has been stored
CREATE TABLE solarhist.dh_datum_meta (
	stream_id	INTEGER GENERATED BY DEFAULT AS IDENTITY,
	created		TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated		TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	node_id		BIGINT NOT NULL,
	source_id	CHARACTER VARYING(64) NOT NULL COLLATE solarhist.naturalsort,
	loc_id		BIGINT,						-- location datum only; NULL for node datum
	names_i		TEXT[],						-- property names; only ever appended to
	names_a		TEXT[],
	names_s		TEXT[],
	type_ids	SMALLINT[],					-- every dh_datum_type.type_id stored in the stream
	CONSTRAINT dh_datum_meta_pk PRIMARY KEY (stream_id),
	CONSTRAINT dh_datum_meta_unq UNIQUE NULLS NOT DISTINCT (node_id, source_id, loc_id)
);

-- time zone of each node, for the local dates of its streams, including location streams
-- stored by the node; the historian of each node stores its zone when it starts, and a node
-- without a row uses UTC, as SolarNet does, so the result never depends on the session zone
--
-- With postgres-init-agg.sql the days and months of the node's aggregates are in this zone:
-- adding, changing or removing a row marks the days of the node's streams stale, so they and
-- their months are computed again from the hourly rows, and an invalid zone is rejected.
CREATE TABLE solarhist.dh_node_time_zone (
	node_id		BIGINT NOT NULL,
	time_zone	TEXT NOT NULL,				-- a zone name Postgres knows, like Pacific/Auckland
	updated		TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT dh_node_time_zone_pk PRIMARY KEY (node_id)
);

-- datum table, partitioned by UTC month; the data_i, data_a, and data_s values are in the same
-- order as the names_i, names_a, and names_s property names of the stream
--
-- The monthly partitions are created by solarhist.dh_datum_ensure_partition(), and there is no
-- DEFAULT partition on purpose: with one Postgres can no longer find the most recent datum of
-- a stream by looking at just the newest partition.
--
-- The stream_id and type_id columns have no foreign keys on purpose: each one would add a row
-- lock on the referenced row, and the WAL for it, to every datum stored.
CREATE TABLE solarhist.dh_datum (
	ts			TIMESTAMP WITH TIME ZONE NOT NULL,
	stream_id	INTEGER NOT NULL,			-- dh_datum_meta.stream_id
	type_id		SMALLINT NOT NULL,			-- dh_datum_type.type_id
	data_i		NUMERIC[],
	data_a		NUMERIC[],
	data_s		JSONB,						-- JSON array, to preserve the type of each value
	data_t		TEXT[],
	CONSTRAINT dh_datum_pk PRIMARY KEY (stream_id, ts)
) PARTITION BY RANGE (ts);

-- for time range queries across all streams
CREATE INDEX dh_datum_ts_idx ON solarhist.dh_datum USING brin (ts)
	WITH (pages_per_range = 16, autosummarize = on);


/**
 * Convert an Ant path pattern into a regular expression.
 *
 * This can be used to convert source ID wildcard patterns into
 * regular expressions that Postgres understands.
 *
 * The result follows Spring's AntPathMatcher, so that patterns are matched the
 * same way here as they are in the application:
 *
 *   ?   matches one character within a path segment
 *   *   matches zero or more characters within a single path segment
 *   **  matches zero or more path segments, but only when it forms a complete
 *       segment; anywhere else it behaves like *
 *
 * A pattern without a leading / never matches a path with one, and vice versa.
 *
 * Patterns and paths that end with a / are not handled exactly as
 * AntPathMatcher handles them; neither source IDs nor metadata paths end with
 * one. URI template variables like {id} are treated as literal text.
 *
 * Copied from the SolarNet solarcommon.ant_pattern_to_regexp() function.
 *
 * @param pat the Ant path pattern to convert
 * @returns the equivalent regular expression
 */
CREATE OR REPLACE FUNCTION solarhist.ant_pattern_to_regexp(pat TEXT)
	RETURNS TEXT LANGUAGE SQL STRICT IMMUTABLE PARALLEL SAFE AS
$$
	WITH escaped AS (
		-- drop the segment marker used below, then escape regexp metacharacters
		-- and expand "?" into one character within a segment
		SELECT regexp_replace(
			regexp_replace(
				replace(pat, E'\x01', ''),
			'([!$()+.:<=>[\\\]^{|}-])', '\\\1', 'g'),
		E'[?]', E'[^/]', 'g') AS x
	), marked AS (
		-- mark every "**" that forms a complete segment, so the next step skips it
		SELECT regexp_replace(x, E'(^|/)[*][*](?=/|$)', E'\\1\x01', 'g') AS x FROM escaped
	), segments AS (
		-- "*", and any "**" that is not a complete segment, match within one segment
		SELECT regexp_replace(x, E'[*]+', E'[^/]*', 'g') AS x FROM marked
	), collapsed AS (
		-- adjacent "**" segments are equivalent to a single one
		SELECT regexp_replace(x, E'\x01(/\x01)+', E'\x01', 'g') AS x FROM segments
	), expanded AS (
		-- a "**" segment matches zero or more segments, in any position
		SELECT regexp_replace(
			regexp_replace(
				regexp_replace(
					replace(x, E'\x01', '.*'),
				E'/[.][*]/', '(/|/.*/)', 'g'),
			E'/[.][*]$', '(/.*)?'),
		E'^[.][*]/', '(.*/)?') AS x FROM collapsed
	)
	-- a pattern only matches a path that agrees on the leading separator
	SELECT '^' || CASE WHEN left(pat, 1) = '/' THEN '' ELSE '(?![/])' END || x || '$'
	FROM expanded;
$$;


/**
 * Convert a list of Ant path patterns into regular expressions.
 *
 * Copied from the SolarNet solarcommon.ant_patterns_to_regexps() function.
 *
 * @param pats the Ant path patterns to convert
 * @returns the equivalent regular expressions
 * @see solarhist.ant_pattern_to_regexp()
 */
CREATE OR REPLACE FUNCTION solarhist.ant_patterns_to_regexps(pats TEXT[])
	RETURNS TEXT[] LANGUAGE SQL STRICT IMMUTABLE PARALLEL SAFE AS
$$
	SELECT ARRAY(SELECT solarhist.ant_pattern_to_regexp(p) FROM unnest(pats) p);
$$;


/**
 * Create the monthly `solarhist.dh_datum` partition that holds a given date, if it does not
 * already exist.
 *
 * Partitions cover one UTC month and are named like `solarhist.dh_datum_2026_11`. A new
 * partition is created as a table of its own and then attached, because that does not block
 * other transactions from reading and writing `solarhist.dh_datum` while it happens.
 *
 * @param ts_at the date to ensure a partition exists for
 */
CREATE OR REPLACE FUNCTION solarhist.dh_datum_ensure_partition(ts_at TIMESTAMP WITH TIME ZONE)
	RETURNS VOID LANGUAGE plpgsql VOLATILE AS
$$
DECLARE
	ts_start	CONSTANT TIMESTAMP WITH TIME ZONE := date_trunc('month', ts_at, 'UTC');
	ts_end		CONSTANT TIMESTAMP WITH TIME ZONE := date_add(ts_start, INTERVAL 'P1M', 'UTC');
	part_name	CONSTANT TEXT := 'dh_datum_' || to_char(ts_start AT TIME ZONE 'UTC', 'YYYY_MM');
BEGIN
	IF to_regclass('solarhist.' || part_name) IS NOT NULL THEN
		RETURN;
	END IF;

	-- let one caller at a time past here; this is the same lock ATTACH PARTITION takes
	LOCK TABLE ONLY solarhist.dh_datum IN SHARE UPDATE EXCLUSIVE MODE;

	-- look again, as another caller could have created the partition while this one waited
	IF to_regclass('solarhist.' || part_name) IS NULL THEN
		EXECUTE format(
			'CREATE TABLE solarhist.%I (LIKE solarhist.dh_datum INCLUDING DEFAULTS INCLUDING CONSTRAINTS)'
			, part_name);
		EXECUTE format(
			'ALTER TABLE solarhist.dh_datum ATTACH PARTITION solarhist.%I FOR VALUES FROM (%L) TO (%L)'
			, part_name, ts_start, ts_end);
	END IF;
END
$$;


/**
 * Get the ID of a datum type, registering the type in the `solarhist.dh_datum_type` table if
 * it does not already exist.
 *
 * The type names of an existing type are replaced if they differ from the given names, so
 * the registry follows changes made to the class over time.
 *
 * @param cname		the datum class name
 * @param tnames	the names of all classes and interfaces the datum class can be assigned to,
 * 					including the datum class itself
 * @returns the type ID, to pass to `solarhist.dh_store_datum()`
 */
CREATE OR REPLACE FUNCTION solarhist.dh_store_datum_type(
		cname 			TEXT,
		tnames 			TEXT[]
	) RETURNS SMALLINT LANGUAGE plpgsql VOLATILE AS
$$
DECLARE
	tid 			SMALLINT;
	curr_names		TEXT[];
BEGIN
	-- look first, rather than upsert, so the SMALLINT sequence is not used up by existing types
	SELECT type_id, type_names
	FROM solarhist.dh_datum_type
	WHERE class_name = cname
	INTO tid, curr_names;

	IF NOT FOUND THEN
		INSERT INTO solarhist.dh_datum_type (class_name, type_names)
		VALUES (cname, tnames)
		ON CONFLICT (class_name) DO NOTHING
		RETURNING type_id
		INTO tid;

		IF FOUND THEN
			RETURN tid;
		END IF;

		-- registered concurrently by another transaction
		SELECT type_id, type_names
		FROM solarhist.dh_datum_type
		WHERE class_name = cname
		INTO tid, curr_names;
	END IF;

	IF NOT (curr_names @> tnames AND curr_names <@ tnames) THEN
		UPDATE solarhist.dh_datum_type
		SET type_names = tnames
		WHERE type_id = tid;
	END IF;

	RETURN tid;
END
$$;


/**
 * Add or update a datum record. The data is stored in the `solarhist.dh_datum` table.
 *
 * The stream is registered in the `solarhist.dh_datum_meta` table if it does not already
 * exist. Any property names or datum type new to the stream are added to its
 * `solarhist.dh_datum_meta` row, and the monthly `solarhist.dh_datum` partition for the datum
 * is created if it does not already exist.
 *
 * An instantaneous or accumulating property value that is not a number is stored as `NULL`.
 *
 * Call this in a transaction of its own. The partition is created first, while the
 * transaction holds no other locks, and that is what stops concurrent calls from deadlocking
 * when a partition is needed.
 *
 * @param ddate the datum timestamp
 * @param node 	the node ID
 * @param src 	the source ID
 * @param loc 	the location ID, for location datum, or `NULL` for node datum
 * @param tid 	the datum type ID, from `solarhist.dh_store_datum_type()`
 * @param jdata the datum samples JSON object (with i, a, s, and t properties)
 * @returns the stream ID
 */
CREATE OR REPLACE FUNCTION solarhist.dh_store_datum(
		ddate 			TIMESTAMP WITH TIME ZONE,
		node 			BIGINT,
		src 			TEXT,
		loc 			BIGINT,
		tid 			INTEGER,
		jdata 			TEXT
	) RETURNS INTEGER LANGUAGE plpgsql VOLATILE AS
$$
DECLARE
	ts_crea 		CONSTANT TIMESTAMP WITH TIME ZONE 	:= COALESCE(ddate, CURRENT_TIMESTAMP);
	jdata_json 		CONSTANT JSONB 						:= jsonb_strip_nulls(jdata::jsonb);
	jdata_i 		CONSTANT JSONB := CASE jsonb_typeof(jdata_json->'i') WHEN 'object' THEN jdata_json->'i' END;
	jdata_a 		CONSTANT JSONB := CASE jsonb_typeof(jdata_json->'a') WHEN 'object' THEN jdata_json->'a' END;
	jdata_s 		CONSTANT JSONB := CASE jsonb_typeof(jdata_json->'s') WHEN 'object' THEN jdata_json->'s' END;
	jdata_t 		CONSTANT JSONB := CASE jsonb_typeof(jdata_json->'t') WHEN 'array' THEN jdata_json->'t' END;

	-- datum property names
	k_i 			CONSTANT TEXT[] := ARRAY(SELECT jsonb_object_keys(jdata_i));
	k_a 			CONSTANT TEXT[] := ARRAY(SELECT jsonb_object_keys(jdata_a));
	k_s 			CONSTANT TEXT[] := ARRAY(SELECT jsonb_object_keys(jdata_s));

	sid 			INTEGER;

	-- stream property names and datum types
	p_i 			TEXT[];
	p_a 			TEXT[];
	p_s 			TEXT[];
	t_ids 			SMALLINT[];

	-- property values
	v_i 			NUMERIC[];
	v_a 			NUMERIC[];
	v_s 			JSONB;
BEGIN
	PERFORM solarhist.dh_datum_ensure_partition(ts_crea);

	-- get, or create, stream
	SELECT stream_id, names_i, names_a, names_s, type_ids
	FROM solarhist.dh_datum_meta
	WHERE node_id = node AND source_id = src AND loc_id IS NOT DISTINCT FROM loc
	INTO sid, p_i, p_a, p_s, t_ids;

	IF NOT FOUND THEN
		INSERT INTO solarhist.dh_datum_meta (node_id, source_id, loc_id)
		VALUES (node, src, loc)
		ON CONFLICT (node_id, source_id, loc_id) DO NOTHING
		RETURNING stream_id
		INTO sid;

		IF NOT FOUND THEN
			-- created concurrently by another transaction
			SELECT stream_id, names_i, names_a, names_s, type_ids
			FROM solarhist.dh_datum_meta
			WHERE node_id = node AND source_id = src AND loc_id IS NOT DISTINCT FROM loc
			INTO sid, p_i, p_a, p_s, t_ids;
		END IF;
	END IF;

	-- add any property names and datum type new to the stream
	IF (tid = ANY(t_ids)) IS NOT TRUE
			OR NOT (k_i <@ COALESCE(p_i, '{}') AND k_a <@ COALESCE(p_a, '{}') AND k_s <@ COALESCE(p_s, '{}')) THEN
		-- stands in for a foreign key on type_id, without checking for every datum stored
		IF NOT EXISTS (SELECT 1 FROM solarhist.dh_datum_type WHERE type_id = tid) THEN
			RAISE EXCEPTION 'Datum type % does not exist.', tid
			USING ERRCODE = 'foreign_key_violation';
		END IF;

		-- test against the row values, as another transaction could have added the same name or type
		UPDATE solarhist.dh_datum_meta SET updated = CURRENT_TIMESTAMP
			, names_i = array_cat(names_i, (SELECT array_agg(k) FROM unnest(k_i) k WHERE array_position(names_i, k) IS NULL))
			, names_a = array_cat(names_a, (SELECT array_agg(k) FROM unnest(k_a) k WHERE array_position(names_a, k) IS NULL))
			, names_s = array_cat(names_s, (SELECT array_agg(k) FROM unnest(k_s) k WHERE array_position(names_s, k) IS NULL))
			, type_ids = CASE WHEN tid = ANY(type_ids) THEN type_ids ELSE array_append(type_ids, tid::SMALLINT) END
		WHERE stream_id = sid
		RETURNING names_i, names_a, names_s
		INTO p_i, p_a, p_s;
	END IF;

	-- order property values by the stream property names, without any trailing NULL values;
	-- an instantaneous or accumulating value that is not a number is stored as NULL
	WITH p AS (
		SELECT o, CASE WHEN pg_input_is_valid(jdata_i->>n, 'numeric') THEN (jdata_i->>n)::NUMERIC END AS v
		FROM unnest(p_i) WITH ORDINALITY AS t(n, o)
	)
	SELECT array_agg(v ORDER BY o)
	FROM p
	WHERE o <= (SELECT max(o) FROM p WHERE v IS NOT NULL)
	INTO v_i;

	WITH p AS (
		SELECT o, CASE WHEN pg_input_is_valid(jdata_a->>n, 'numeric') THEN (jdata_a->>n)::NUMERIC END AS v
		FROM unnest(p_a) WITH ORDINALITY AS t(n, o)
	)
	SELECT array_agg(v ORDER BY o)
	FROM p
	WHERE o <= (SELECT max(o) FROM p WHERE v IS NOT NULL)
	INTO v_a;

	WITH p AS (
		SELECT o, jdata_s->n AS v
		FROM unnest(p_s) WITH ORDINALITY AS t(n, o)
	)
	SELECT jsonb_agg(v ORDER BY o)
	FROM p
	WHERE o <= (SELECT max(o) FROM p WHERE v IS NOT NULL)
	INTO v_s;

	INSERT INTO solarhist.dh_datum (stream_id, ts, type_id, data_i, data_a, data_s, data_t)
	VALUES (
		sid
		, ts_crea
		, tid
		, v_i
		, v_a
		, v_s
		, (SELECT array_agg(e) FROM jsonb_array_elements_text(jdata_t) e WHERE e IS NOT NULL)
	)
	ON CONFLICT (stream_id, ts) DO UPDATE
	SET type_id = EXCLUDED.type_id,
		data_i = EXCLUDED.data_i,
		data_a = EXCLUDED.data_a,
		data_s = EXCLUDED.data_s,
		data_t = EXCLUDED.data_t;

	RETURN sid;
END
$$;


/* ============================================================================
 * Reading difference support.
 *
 * Ported from the SolarNet solardatm schema, without SolarNet's Reset
 * auxiliary records. These need no extension, so a `Difference` reading query
 * without aggregation works on every deployment. The aggregate setup script,
 * postgres-init-agg.sql, replaces solarhist.dh_find_datum_diff_near_rows() with
 * a version that falls back to hourly readings where raw datum have been
 * dropped.
 * ============================================================================
 */

-- datum row type used by the functions below regardless of physical table; like the SolarNet
-- solardatm.datm_rec type, without the rtype column used for Reset records
CREATE TYPE solarhist.dh_datum_rec AS (
	stream_id	INTEGER,
	ts			TIMESTAMP WITH TIME ZONE,
	data_i		NUMERIC[],
	data_a		NUMERIC[],
	data_s		JSONB,
	data_t		TEXT[]
);

-- the state and result of the solarhist.dh_diff_datum() aggregate; like the SolarNet
-- solardatm.agg_datm_diff type
CREATE TYPE solarhist.dh_agg_datum_diff AS (
	stream_id	INTEGER,
	ts_start	TIMESTAMP WITH TIME ZONE,
	ts_end		TIMESTAMP WITH TIME ZONE,
	data_i		NUMERIC[],
	data_a		NUMERIC[],
	data_s		JSONB,
	data_t		TEXT[],
	stat_i		NUMERIC[][],
	read_a		NUMERIC[][]
);


/**
 * Reduce a two-dimensional array into a set of one-dimensional arrays.
 *
 * Copied from the SolarNet solarcommon.reduce_dim() function.
 *
 * @param the two-dimensional array
 * @returns each slice of the first dimension
 */
CREATE OR REPLACE FUNCTION solarhist.reduce_dim(anyarray)
	RETURNS SETOF anyarray LANGUAGE plpgsql IMMUTABLE STRICT ROWS 20 AS
$$
DECLARE
	s $1%TYPE;
BEGIN
	FOREACH s SLICE 1 IN ARRAY $1 LOOP
		RETURN NEXT s;
	END LOOP;
	RETURN;
END
$$;


/**
 * Find the time of the datum immediately before a given time, within a cutoff.
 *
 * This function exists so that the planner is given a full date constraint on
 * `solarhist.dh_datum`. Ported from the SolarNet solardatm.find_time_before_ts() function.
 *
 * @param sid 		the stream ID
 * @param ts_at		the time to look before (exclusive)
 * @param cutoff 	the earliest time to consider (inclusive)
 * @param must_a	if `TRUE` then only consider datum with accumulating values
 * @param has_no_a	`TRUE` if the stream can be assumed to have no accumulating properties
 * @returns the time of the datum found, or no row
 */
CREATE OR REPLACE FUNCTION solarhist.dh_find_time_before_ts(
		sid 		INTEGER,
		ts_at 		TIMESTAMP WITH TIME ZONE,
		cutoff 		TIMESTAMP WITH TIME ZONE,
		must_a		BOOLEAN DEFAULT FALSE,
		has_no_a 	BOOLEAN DEFAULT FALSE
	) RETURNS SETOF TIMESTAMP WITH TIME ZONE LANGUAGE plpgsql STRICT STABLE ROWS 1 AS
$$
BEGIN
	RETURN QUERY
	SELECT ts
	FROM solarhist.dh_datum
	WHERE stream_id = sid
		AND ts < ts_at
		AND ts >= cutoff
		AND NOT(must_a AND (has_no_a OR data_a IS NULL))
	ORDER BY ts DESC
	LIMIT 1;
END
$$;


/**
 * Find the time of the datum immediately after a given time, within a cutoff.
 *
 * This function exists so that the planner is given a full date constraint on
 * `solarhist.dh_datum`. Ported from the SolarNet solardatm.find_time_after_ts() function.
 *
 * @param sid 		the stream ID
 * @param ts_at		the time to look after (exclusive)
 * @param cutoff 	the latest time to consider (inclusive)
 * @param must_a	if `TRUE` then only consider datum with accumulating values
 * @param has_no_a	`TRUE` if the stream can be assumed to have no accumulating properties
 * @returns the time of the datum found, or no row
 */
CREATE OR REPLACE FUNCTION solarhist.dh_find_time_after_ts(
		sid 		INTEGER,
		ts_at 		TIMESTAMP WITH TIME ZONE,
		cutoff 		TIMESTAMP WITH TIME ZONE,
		must_a		BOOLEAN DEFAULT FALSE,
		has_no_a 	BOOLEAN DEFAULT FALSE
	) RETURNS SETOF TIMESTAMP WITH TIME ZONE LANGUAGE plpgsql STRICT STABLE ROWS 1 AS
$$
BEGIN
	RETURN QUERY
	SELECT ts
	FROM solarhist.dh_datum
	WHERE stream_id = sid
		AND ts > ts_at
		AND ts <= cutoff
		AND NOT(must_a AND (has_no_a OR data_a IS NULL))
	ORDER BY ts
	LIMIT 1;
END
$$;


/**
 * Find if the datum at a given time has accumulating values.
 *
 * Ported from the SolarNet solardatm.datm_has_accumulating_at() function.
 *
 * @param sid 		the stream ID
 * @param ts_at		the datum time
 * @returns the datum time and whether it has accumulating values, or no row if there is no
 *          datum at that time
 */
CREATE OR REPLACE FUNCTION solarhist.dh_datum_has_accumulating_at(
		sid 		INTEGER,
		ts_at 		TIMESTAMP WITH TIME ZONE
	) RETURNS TABLE (
		ts 			TIMESTAMP WITH TIME ZONE,
		has_a 		BOOLEAN
	) LANGUAGE plpgsql STRICT STABLE ROWS 1 AS
$$
BEGIN
	RETURN QUERY
	SELECT d.ts, COALESCE(CARDINALITY(d.data_a) > 0, FALSE) AS has_a
	FROM solarhist.dh_datum d
	WHERE d.stream_id = sid
		AND d.ts = ts_at;
END
$$;


/**
 * Find datum between two times, inclusive at both ends.
 *
 * This function exists so that the planner is given a full date constraint on
 * `solarhist.dh_datum`: its query is planned with the times as values, so only the partitions
 * they fall in are scanned. The SQL functions that the planner inlines into the calling query
 * use it to look up datum by times found while that query runs, as a join on such times would
 * be planned over every partition. Ported from the SolarNet solardatm.find_datm_between()
 * function.
 *
 * @param sid 		the stream ID
 * @param start_ts	the minimum time (inclusive)
 * @param end_ts 	the maximum time (inclusive)
 * @returns the datum
 */
CREATE OR REPLACE FUNCTION solarhist.dh_find_datum_between(
		sid 		INTEGER,
		start_ts 	TIMESTAMP WITH TIME ZONE,
		end_ts 		TIMESTAMP WITH TIME ZONE
	) RETURNS SETOF solarhist.dh_datum_rec LANGUAGE plpgsql STRICT STABLE ROWS 500 AS
$$
BEGIN
	RETURN QUERY
	SELECT stream_id, ts, data_i, data_a, data_s, data_t
	FROM solarhist.dh_datum
	WHERE stream_id = sid
		AND ts >= start_ts
		AND ts <= end_ts;
END
$$;


/**
 * Find the datum immediately before and after a point in time, within a tolerance.
 *
 * If a datum exists exactly at the given time, that datum alone is returned. Otherwise up to
 * two datum are returned, one before and one after the given time.
 *
 * Looking for a datum with accumulating values is slow when there is none, so the search
 * before is first made over at most 14 days. If nothing is found there, the latest datum
 * before those 14 days and within the tolerance is used, unless `must_a` is `TRUE` and it has
 * no accumulating values: then the latest datum with accumulating values within the 14 days
 * before it, and within the tolerance, is used instead. Ported from the SolarNet
 * solardatm.find_datm_around_ts() function, with its NET-538 changes.
 *
 * It is not declared STRICT, so the planner can inline it into the calling query and prune the
 * `solarhist.dh_datum` partitions while planning. A NULL argument still gives no rows. For the
 * same reason it looks up the datum at the times it finds with
 * `solarhist.dh_find_datum_between()`, which plans its query with the time as a value: a join
 * on a time found while the query runs would be planned over every partition.
 *
 * @param sid 		the stream ID
 * @param ts_at		the time to find the datum around
 * @param tolerance the maximum time to look before and after `ts_at`
 * @param must_a	if `TRUE` then only consider datum with accumulating values
 * @param has_no_a	`TRUE` if the stream can be assumed to have no accumulating properties
 * @returns the datum found
 */
CREATE OR REPLACE FUNCTION solarhist.dh_find_datum_around_ts(
		sid 		INTEGER,
		ts_at 		TIMESTAMP WITH TIME ZONE,
		tolerance 	INTERVAL DEFAULT INTERVAL 'P1M',
		must_a		BOOLEAN DEFAULT FALSE,
		has_no_a 	BOOLEAN DEFAULT FALSE
	) RETURNS SETOF solarhist.dh_datum_rec LANGUAGE SQL STABLE ROWS 2 AS
$$
	-- find if the stream has accumulating properties at all, to avoid a costly scan
	WITH meta AS (
		SELECT COALESCE(CARDINALITY(names_a) = 0, TRUE) AS has_no_a
		FROM solarhist.dh_datum_meta
		WHERE stream_id = sid
	)
	, exact AS (
		SELECT d.stream_id, d.ts, d.data_i, d.data_a, d.data_s, d.data_t
		FROM solarhist.dh_datum d
		WHERE d.stream_id = sid
			AND d.ts = ts_at
			AND NOT(must_a AND (has_no_a OR d.data_a IS NULL))
	)
	, srange AS (
		SELECT COALESCE(
			(
				-- the datum before, requiring accumulating values, within at most 14 days
				SELECT d.ts
				FROM meta, solarhist.dh_find_time_before_ts(sid, ts_at, ts_at - LEAST(tolerance, INTERVAL 'P14D'), must_a, meta.has_no_a) AS d(ts)
			),
			(
				-- then the datum before over the full tolerance, not requiring accumulating
				-- values, which an index-only scan can find quickly
				WITH way_back AS (
					SELECT d.ts
					FROM meta, solarhist.dh_find_time_before_ts(
						  sid
						, ts_at - LEAST(tolerance, INTERVAL 'P14D')
						, ts_at - tolerance
						, FALSE
						, meta.has_no_a
						) AS d(ts)
				)
				, way_back_d AS (
					SELECT d.ts, d.has_a
					FROM way_back, solarhist.dh_datum_has_accumulating_at(sid, way_back.ts) AS d
				)
				, t AS (
					SELECT COALESCE(
						(
							-- if the way-back datum has accumulating values, or they are not
							-- required, use it
							SELECT ts
							FROM way_back_d
							WHERE has_a OR NOT must_a
						),
						(
							-- otherwise a short search before it, requiring accumulating values,
							-- within the tolerance, unless the stream has none (NET-538)
							SELECT d.ts
							FROM meta, way_back_d, solarhist.dh_find_time_before_ts(
								  sid
								, way_back_d.ts
								, GREATEST(way_back_d.ts - LEAST(tolerance, INTERVAL 'P14D'), ts_at - tolerance)
								, TRUE
								, meta.has_no_a
							) AS d(ts)
							WHERE NOT meta.has_no_a
						)
					) AS ts
				)
				-- a lookup rather than a join, so it is not planned over every partition
				SELECT d.ts
				FROM t, solarhist.dh_find_datum_between(sid, t.ts, t.ts) d
				WHERE (NOT must_a OR d.data_a IS NOT NULL)
			)
		) AS ts

		UNION ALL

		SELECT COALESCE(
			(
				-- the datum after, requiring accumulating values, within at most 14 days
				SELECT d.ts
				FROM meta, solarhist.dh_find_time_after_ts(sid, ts_at, ts_at + LEAST(tolerance, INTERVAL 'P14D'), must_a, meta.has_no_a) AS d(ts)
			),
			(
				-- then the datum after over the full tolerance, not requiring accumulating values
				WITH t AS (
					SELECT d.ts
					FROM meta, solarhist.dh_find_time_after_ts(sid, ts_at, ts_at + tolerance, FALSE, meta.has_no_a) AS d(ts)
				)
				-- a lookup rather than a join, so it is not planned over every partition
				SELECT d.ts
				FROM t, solarhist.dh_find_datum_between(sid, t.ts, t.ts) d
				WHERE (NOT must_a OR d.data_a IS NOT NULL)
			)
		) AS ts
	)
	, b AS (
		SELECT d.*, 0 AS rtype
		FROM exact d

		UNION ALL

		-- a lookup rather than a join, so it is not planned over every partition
		SELECT d.stream_id, d.ts, d.data_i, d.data_a, d.data_s, d.data_t, 1 AS rtype
		FROM srange, solarhist.dh_find_datum_between(sid, srange.ts, srange.ts) d
	)
	, d AS (
		-- the exact datum if there is one, otherwise the datum before and after
		SELECT b.*
			, CASE
				WHEN rtype = 0 THEN TRUE
				WHEN rtype = 1 AND rank() OVER (ORDER BY rtype) = 1 THEN TRUE
				ELSE FALSE
				END AS inc
		FROM b
	)
	SELECT stream_id, ts, data_i, data_a, data_s, data_t
	FROM d
	WHERE inc
		-- a NULL argument gives no rows, as for a STRICT function
		AND num_nulls(sid, ts_at, tolerance, must_a, has_no_a) = 0
$$;


/**
 * Find the datum for calculating the reading difference between two times, within a
 * tolerance.
 *
 * For each of the two times this finds the datum at that time, or the one before it, or
 * failing both the one after it, considering only datum with accumulating values. Pass the
 * results, ordered by time, to the `solarhist.dh_diff_datum()` aggregate. Ported from the
 * SolarNet solardatm.find_datm_diff_near_rows() function, without Reset records.
 *
 * @param sid 		the stream ID
 * @param start_ts	the starting time
 * @param end_ts 	the ending time
 * @param tolerance the maximum time to look before and after each time
 * @returns up to two datum rows, with only the accumulating values
 * @see solarhist.dh_find_datum_diff_rows()
 */
CREATE OR REPLACE FUNCTION solarhist.dh_find_datum_diff_near_rows(
		sid 			INTEGER,
		start_ts 		TIMESTAMP WITH TIME ZONE,
		end_ts 			TIMESTAMP WITH TIME ZONE,
		tolerance 		INTERVAL DEFAULT INTERVAL 'P3M'
	) RETURNS SETOF solarhist.dh_datum_rec LANGUAGE SQL STABLE ROWS 10 AS
$$
	-- find if the stream has accumulating properties at all, to avoid a costly scan
	WITH meta AS (
		SELECT COALESCE(CARDINALITY(names_a) = 0, TRUE) AS has_no_a
		FROM solarhist.dh_datum_meta
		WHERE stream_id = sid
	)
	-- the earliest of the datum around each time, which may be an exact match
	, d AS (
		(
		SELECT d.*
		FROM meta, solarhist.dh_find_datum_around_ts(sid, start_ts, tolerance, TRUE, meta.has_no_a) AS d
		ORDER BY d.ts
		LIMIT 1
		)
		UNION
		(
		SELECT d.*
		FROM meta, solarhist.dh_find_datum_around_ts(sid, end_ts, tolerance, TRUE, meta.has_no_a) AS d
		ORDER BY d.ts
		LIMIT 1
		)
	)
	-- drop any leading row before the last one at or before the start, and any trailing row
	-- after the last one at or before the end
	, ts_range AS (
		SELECT COALESCE(max(ts) FILTER (WHERE ts <= start_ts), start_ts) AS min_ts
			, COALESCE(max(ts) FILTER (WHERE ts <= end_ts), end_ts) AS max_ts
		FROM d
	)
	SELECT d.stream_id
		, d.ts
		, NULL::NUMERIC[] AS data_i
		, d.data_a
		, NULL::JSONB AS data_s
		, NULL::TEXT[] AS data_t
	FROM d, ts_range
	WHERE d.ts >= ts_range.min_ts AND d.ts <= ts_range.max_ts
$$;


/**
 * Find the datum for calculating the reading difference between two times, looking up to one
 * year before and after each time.
 *
 * Ported from the SolarNet solardatm.find_datm_diff_rows() function.
 *
 * @param sid 		the stream ID
 * @param start_ts	the starting time
 * @param end_ts 	the ending time
 * @returns up to two datum rows, with only the accumulating values
 * @see solarhist.dh_find_datum_diff_near_rows()
 */
CREATE OR REPLACE FUNCTION solarhist.dh_find_datum_diff_rows(
		sid 			INTEGER,
		start_ts 		TIMESTAMP WITH TIME ZONE,
		end_ts 			TIMESTAMP WITH TIME ZONE
	) RETURNS SETOF solarhist.dh_datum_rec LANGUAGE SQL STABLE ROWS 10 AS
$$
	SELECT * FROM solarhist.dh_find_datum_diff_near_rows(sid, start_ts, end_ts, INTERVAL 'P1Y')
$$;


/**
 * State transition function of the `solarhist.dh_diff_datum()` aggregate.
 *
 * Ported from the SolarNet solardatm.diff_datm_sfunc() function, without Reset records.
 *
 * @see solarhist.dh_diff_datum_ffunc()
 */
CREATE OR REPLACE FUNCTION solarhist.dh_diff_datum_sfunc(
		agg_state 	solarhist.dh_agg_datum_diff,
		el 			solarhist.dh_datum_rec
	) RETURNS solarhist.dh_agg_datum_diff LANGUAGE plpgsql IMMUTABLE AS
$$
BEGIN
	WITH wi AS (
		SELECT
			  p.idx
			, p.val AS val
			, s.stat[1] AS cnt
			, s.stat[2] AS val_min
			, s.stat[3] AS val_max
		FROM unnest(agg_state.data_i) WITH ORDINALITY AS p(val, idx)
		INNER JOIN solarhist.reduce_dim(agg_state.stat_i) WITH ORDINALITY AS s(stat, idx) ON s.idx = p.idx
		UNION ALL
		SELECT
			  p.idx
			, p.val
			, 1 AS cnt
			, p.val AS val_min
			, p.val AS val_max
		FROM unnest(el.data_i) WITH ORDINALITY AS p(val, idx)
	)
	, di AS (
		SELECT
			idx
			, sum(val) AS val
			, sum(cnt) AS cnt
			, min(val_min) AS val_min
			, max(val_max) AS val_max
		FROM wi
		GROUP BY idx
	)
	, di_ary AS (
		SELECT
			  array_agg(val ORDER BY idx) AS data_i
			, array_agg(
				ARRAY[cnt, val_min, val_max] ORDER BY idx
			) AS stat_i
		FROM di
	)
	-- accumulating values per property: rtype 0 is the state so far, 1 the new row
	, wa AS (
		SELECT
			  p.idx
			, p.val
			, s.stat[2] AS val_start
			, s.stat[3] AS val_end
			, 0 AS rtype
		FROM unnest(agg_state.data_a) WITH ORDINALITY AS p(val, idx)
		INNER JOIN solarhist.reduce_dim(agg_state.read_a) WITH ORDINALITY AS s(stat, idx) ON s.idx = p.idx
		UNION ALL
		SELECT
			  p.idx
			, p.val
			, NULL::NUMERIC AS val_start
			, NULL::NUMERIC AS val_end
			, 1 AS rtype
		FROM unnest(el.data_a) WITH ORDINALITY AS p(val, idx)
	)
	, da AS (
		SELECT
			idx
			-- previous difference + (current value - previous end)
			, COALESCE(min(val) FILTER (WHERE rtype = 0), 0)
				+ min(val) FILTER (WHERE rtype = 1)
				- COALESCE(min(val_end) FILTER (WHERE rtype = 0), min(val) FILTER (WHERE rtype = 1))
				AS val

			-- start value as the first value
			, COALESCE(min(val_start) FILTER (WHERE rtype = 0), min(val) FILTER (WHERE rtype = 1)) AS val_start

			-- end value as the current value, falling back to the previous end
			, COALESCE(min(val) FILTER (WHERE rtype = 1), min(val_end) FILTER (WHERE rtype = 0)) AS val_end
		FROM wa
		GROUP BY idx
	)
	, da_ary AS (
		SELECT
			  array_agg(val ORDER BY idx) AS data_a
			, array_agg(
				ARRAY[val, val_start, val_end] ORDER BY idx
			) AS read_a
		FROM da
	)
	-- status values are not supported, as SolarNet does not support them here either
	, dt_ary AS (
		SELECT array_agg(DISTINCT val) AS data_t
		FROM (
			SELECT val
			FROM unnest(agg_state.data_t) t(val)
			UNION ALL
			SELECT val
			FROM unnest(el.data_t) t(val)
		) t
		WHERE val IS NOT NULL
	)
	SELECT
		  COALESCE(agg_state.stream_id, el.stream_id)
		, COALESCE(agg_state.ts_start, el.ts)
		, el.ts AS ts_end
		, di_ary.data_i
		, da_ary.data_a
		, NULL::JSONB AS data_s
		, dt_ary.data_t
		, di_ary.stat_i
		, da_ary.read_a
	FROM di_ary, da_ary, dt_ary
	INTO agg_state;

	RETURN agg_state;
END
$$;


/**
 * Final function of the `solarhist.dh_diff_datum()` aggregate.
 *
 * Ported from the SolarNet solardatm.diff_datm_ffunc() function.
 *
 * @see solarhist.dh_diff_datum_sfunc()
 */
CREATE OR REPLACE FUNCTION solarhist.dh_diff_datum_ffunc(
		agg_state 	solarhist.dh_agg_datum_diff
	) RETURNS solarhist.dh_agg_datum_diff LANGUAGE plpgsql STRICT IMMUTABLE AS
$$
BEGIN
	WITH di AS (
		SELECT
			  p.idx
			, to_char(p.val / s.stat[1], 'FM999999999999999999999999999999999999990.999999999')::NUMERIC AS val
			, s.stat[1] AS cnt
			, s.stat[2] AS val_min
			, s.stat[3] AS val_max
		FROM unnest(agg_state.data_i) WITH ORDINALITY AS p(val, idx)
		INNER JOIN solarhist.reduce_dim(agg_state.stat_i) WITH ORDINALITY AS s(stat, idx) ON s.idx = p.idx
	)
	, di_ary AS (
		SELECT
			  array_agg(val ORDER BY idx) AS data_i
			, array_agg(
				ARRAY[cnt, val_min, val_max] ORDER BY idx
			) AS stat_i
		FROM di
	)
	, da AS (
		SELECT
			  p.idx
			, to_char(p.val, 'FM999999999999999999999999999999999999990.999999999')::NUMERIC AS val
		FROM unnest(agg_state.data_a) WITH ORDINALITY AS p(val, idx)
	)
	, da_ary AS (
		SELECT
			  array_agg(val ORDER BY idx) AS data_a
		FROM da
	)
	SELECT
		  agg_state.stream_id
		, agg_state.ts_start
		, agg_state.ts_end
		, di_ary.data_i
		, da_ary.data_a
		, agg_state.data_s
		, agg_state.data_t
		, di_ary.stat_i
		, agg_state.read_a
	FROM di_ary, da_ary
	INTO agg_state;

	RETURN agg_state;
END
$$;


/**
 * Reading difference aggregate, over datum rows ordered by time.
 *
 * The result holds, for each accumulating property, the difference in `data_a` and the
 * difference, starting reading, and ending reading in `read_a`. For example, for the
 * `Difference` reading type without aggregation:
 *
 * 	SELECT (solarhist.dh_diff_datum(d ORDER BY d.ts)).*
 * 	FROM solarhist.dh_find_datum_diff_rows(1, '2026-11-01Z', '2026-11-02Z') d
 *
 * Ported from the SolarNet solardatm.diff_datm() aggregate.
 */
CREATE AGGREGATE solarhist.dh_diff_datum(solarhist.dh_datum_rec) (
	stype 		= solarhist.dh_agg_datum_diff,
	sfunc 		= solarhist.dh_diff_datum_sfunc,
	finalfunc 	= solarhist.dh_diff_datum_ffunc
);
