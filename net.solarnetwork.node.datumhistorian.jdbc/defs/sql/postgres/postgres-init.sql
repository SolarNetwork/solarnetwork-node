/* ============================================================================
 * SQL script to create the tables and functions used by the JDBC
 * DatumHistorian. Requires Postgres 17 or later.
 *
 * Run this as the database role SolarNode connects with, or as a role that
 * role is a member of: solarhist.dh_store_datum() adds partitions to the
 * solarhist.dh_datum table as needed.
 * ============================================================================
 */

CREATE SCHEMA IF NOT EXISTS solarhist;

-- datum type registry: one row per datum class that has been stored
CREATE TABLE solarhist.dh_datum_type (
	type_id		SMALLINT GENERATED BY DEFAULT AS IDENTITY,
	created		TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	class_name	TEXT NOT NULL,				-- datum class name
	type_names	TEXT[] NOT NULL,			-- names of all classes/interfaces the class can be assigned to
	CONSTRAINT dh_datum_type_pk PRIMARY KEY (type_id),
	CONSTRAINT dh_datum_type_unq UNIQUE (class_name)
);

-- datum stream registry: one row per node + source (+ location) that has been stored
CREATE TABLE solarhist.dh_datum_meta (
	stream_id	INTEGER GENERATED BY DEFAULT AS IDENTITY,
	created		TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated		TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	node_id		BIGINT NOT NULL,
	source_id	CHARACTER VARYING(64) NOT NULL,
	loc_id		BIGINT,						-- location datum only; NULL for node datum
	names_i		TEXT[],						-- property names; only ever appended to
	names_a		TEXT[],
	names_s		TEXT[],
	type_ids	SMALLINT[],					-- every dh_datum_type.type_id stored in the stream
	CONSTRAINT dh_datum_meta_pk PRIMARY KEY (stream_id),
	CONSTRAINT dh_datum_meta_unq UNIQUE NULLS NOT DISTINCT (node_id, source_id, loc_id)
);

-- datum table, partitioned by UTC month; the data_i, data_a, and data_s values are in the same
-- order as the names_i, names_a, and names_s property names of the stream
--
-- The monthly partitions are created by solarhist.dh_datum_ensure_partition(), and there is no
-- DEFAULT partition on purpose: with one Postgres can no longer find the most recent datum of
-- a stream by looking at just the newest partition.
--
-- The stream_id and type_id columns have no foreign keys on purpose: each one would add a row
-- lock on the referenced row, and the WAL for it, to every datum stored.
CREATE TABLE solarhist.dh_datum (
	ts			TIMESTAMP WITH TIME ZONE NOT NULL,
	stream_id	INTEGER NOT NULL,			-- dh_datum_meta.stream_id
	type_id		SMALLINT NOT NULL,			-- dh_datum_type.type_id
	data_i		NUMERIC[],
	data_a		NUMERIC[],
	data_s		JSONB,						-- JSON array, to preserve the type of each value
	data_t		TEXT[],
	CONSTRAINT dh_datum_pk PRIMARY KEY (stream_id, ts)
) PARTITION BY RANGE (ts);

-- for time range queries across all streams
CREATE INDEX dh_datum_ts_idx ON solarhist.dh_datum USING brin (ts)
	WITH (pages_per_range = 16, autosummarize = on);


/**
 * Create the monthly `solarhist.dh_datum` partition that holds a given date, if it does not
 * already exist.
 *
 * Partitions cover one UTC month and are named like `solarhist.dh_datum_2026_11`. A new
 * partition is created as a table of its own and then attached, because that does not block
 * other transactions from reading and writing `solarhist.dh_datum` while it happens.
 *
 * @param ts_at the date to ensure a partition exists for
 */
CREATE OR REPLACE FUNCTION solarhist.dh_datum_ensure_partition(ts_at TIMESTAMP WITH TIME ZONE)
	RETURNS VOID LANGUAGE plpgsql VOLATILE AS
$$
DECLARE
	ts_start	CONSTANT TIMESTAMP WITH TIME ZONE := date_trunc('month', ts_at, 'UTC');
	ts_end		CONSTANT TIMESTAMP WITH TIME ZONE := date_add(ts_start, INTERVAL 'P1M', 'UTC');
	part_name	CONSTANT TEXT := 'dh_datum_' || to_char(ts_start AT TIME ZONE 'UTC', 'YYYY_MM');
BEGIN
	IF to_regclass('solarhist.' || part_name) IS NOT NULL THEN
		RETURN;
	END IF;

	-- let one caller at a time past here; this is the same lock ATTACH PARTITION takes
	LOCK TABLE ONLY solarhist.dh_datum IN SHARE UPDATE EXCLUSIVE MODE;

	-- look again, as another caller could have created the partition while this one waited
	IF to_regclass('solarhist.' || part_name) IS NULL THEN
		EXECUTE format(
			'CREATE TABLE solarhist.%I (LIKE solarhist.dh_datum INCLUDING DEFAULTS INCLUDING CONSTRAINTS)'
			, part_name);
		EXECUTE format(
			'ALTER TABLE solarhist.dh_datum ATTACH PARTITION solarhist.%I FOR VALUES FROM (%L) TO (%L)'
			, part_name, ts_start, ts_end);
	END IF;
END
$$;


/**
 * Get the ID of a datum type, registering the type in the `solarhist.dh_datum_type` table if
 * it does not already exist.
 *
 * The type names of an existing type are replaced if they differ from the given names, so
 * the registry follows changes made to the class over time.
 *
 * @param cname		the datum class name
 * @param tnames	the names of all classes and interfaces the datum class can be assigned to,
 * 					including the datum class itself
 * @returns the type ID, to pass to `solarhist.dh_store_datum()`
 */
CREATE OR REPLACE FUNCTION solarhist.dh_store_datum_type(
		cname 			TEXT,
		tnames 			TEXT[]
	) RETURNS SMALLINT LANGUAGE plpgsql VOLATILE AS
$$
DECLARE
	tid 			SMALLINT;
	curr_names		TEXT[];
BEGIN
	-- look first, rather than upsert, so the SMALLINT sequence is not used up by existing types
	SELECT type_id, type_names
	FROM solarhist.dh_datum_type
	WHERE class_name = cname
	INTO tid, curr_names;

	IF NOT FOUND THEN
		INSERT INTO solarhist.dh_datum_type (class_name, type_names)
		VALUES (cname, tnames)
		ON CONFLICT (class_name) DO NOTHING
		RETURNING type_id
		INTO tid;

		IF FOUND THEN
			RETURN tid;
		END IF;

		-- registered concurrently by another transaction
		SELECT type_id, type_names
		FROM solarhist.dh_datum_type
		WHERE class_name = cname
		INTO tid, curr_names;
	END IF;

	IF NOT (curr_names @> tnames AND curr_names <@ tnames) THEN
		UPDATE solarhist.dh_datum_type
		SET type_names = tnames
		WHERE type_id = tid;
	END IF;

	RETURN tid;
END
$$;


/**
 * Add or update a datum record. The data is stored in the `solarhist.dh_datum` table.
 *
 * The stream is registered in the `solarhist.dh_datum_meta` table if it does not already
 * exist. Any property names or datum type new to the stream are added to its
 * `solarhist.dh_datum_meta` row, and the monthly `solarhist.dh_datum` partition for the datum
 * is created if it does not already exist.
 *
 * An instantaneous or accumulating property value that is not a number is stored as `NULL`.
 *
 * Call this in a transaction of its own. The partition is created first, while the
 * transaction holds no other locks, and that is what stops concurrent calls from deadlocking
 * when a partition is needed.
 *
 * @param ddate the datum timestamp
 * @param node 	the node ID
 * @param src 	the source ID
 * @param loc 	the location ID, for location datum, or `NULL` for node datum
 * @param tid 	the datum type ID, from `solarhist.dh_store_datum_type()`
 * @param jdata the datum samples JSON object (with i, a, s, and t properties)
 * @returns the stream ID
 */
CREATE OR REPLACE FUNCTION solarhist.dh_store_datum(
		ddate 			TIMESTAMP WITH TIME ZONE,
		node 			BIGINT,
		src 			TEXT,
		loc 			BIGINT,
		tid 			INTEGER,
		jdata 			TEXT
	) RETURNS INTEGER LANGUAGE plpgsql VOLATILE AS
$$
DECLARE
	ts_crea 		CONSTANT TIMESTAMP WITH TIME ZONE 	:= COALESCE(ddate, CURRENT_TIMESTAMP);
	jdata_json 		CONSTANT JSONB 						:= jsonb_strip_nulls(jdata::jsonb);
	jdata_i 		CONSTANT JSONB := CASE jsonb_typeof(jdata_json->'i') WHEN 'object' THEN jdata_json->'i' END;
	jdata_a 		CONSTANT JSONB := CASE jsonb_typeof(jdata_json->'a') WHEN 'object' THEN jdata_json->'a' END;
	jdata_s 		CONSTANT JSONB := CASE jsonb_typeof(jdata_json->'s') WHEN 'object' THEN jdata_json->'s' END;
	jdata_t 		CONSTANT JSONB := CASE jsonb_typeof(jdata_json->'t') WHEN 'array' THEN jdata_json->'t' END;

	-- datum property names
	k_i 			CONSTANT TEXT[] := ARRAY(SELECT jsonb_object_keys(jdata_i));
	k_a 			CONSTANT TEXT[] := ARRAY(SELECT jsonb_object_keys(jdata_a));
	k_s 			CONSTANT TEXT[] := ARRAY(SELECT jsonb_object_keys(jdata_s));

	sid 			INTEGER;

	-- stream property names and datum types
	p_i 			TEXT[];
	p_a 			TEXT[];
	p_s 			TEXT[];
	t_ids 			SMALLINT[];

	-- property values
	v_i 			NUMERIC[];
	v_a 			NUMERIC[];
	v_s 			JSONB;
BEGIN
	PERFORM solarhist.dh_datum_ensure_partition(ts_crea);

	-- get, or create, stream
	SELECT stream_id, names_i, names_a, names_s, type_ids
	FROM solarhist.dh_datum_meta
	WHERE node_id = node AND source_id = src AND loc_id IS NOT DISTINCT FROM loc
	INTO sid, p_i, p_a, p_s, t_ids;

	IF NOT FOUND THEN
		INSERT INTO solarhist.dh_datum_meta (node_id, source_id, loc_id)
		VALUES (node, src, loc)
		ON CONFLICT (node_id, source_id, loc_id) DO NOTHING
		RETURNING stream_id
		INTO sid;

		IF NOT FOUND THEN
			-- created concurrently by another transaction
			SELECT stream_id, names_i, names_a, names_s, type_ids
			FROM solarhist.dh_datum_meta
			WHERE node_id = node AND source_id = src AND loc_id IS NOT DISTINCT FROM loc
			INTO sid, p_i, p_a, p_s, t_ids;
		END IF;
	END IF;

	-- add any property names and datum type new to the stream
	IF (tid = ANY(t_ids)) IS NOT TRUE
			OR NOT (k_i <@ COALESCE(p_i, '{}') AND k_a <@ COALESCE(p_a, '{}') AND k_s <@ COALESCE(p_s, '{}')) THEN
		-- stands in for a foreign key on type_id, without checking for every datum stored
		IF NOT EXISTS (SELECT 1 FROM solarhist.dh_datum_type WHERE type_id = tid) THEN
			RAISE EXCEPTION 'Datum type % does not exist.', tid
			USING ERRCODE = 'foreign_key_violation';
		END IF;

		-- test against the row values, as another transaction could have added the same name or type
		UPDATE solarhist.dh_datum_meta SET updated = CURRENT_TIMESTAMP
			, names_i = array_cat(names_i, (SELECT array_agg(k) FROM unnest(k_i) k WHERE array_position(names_i, k) IS NULL))
			, names_a = array_cat(names_a, (SELECT array_agg(k) FROM unnest(k_a) k WHERE array_position(names_a, k) IS NULL))
			, names_s = array_cat(names_s, (SELECT array_agg(k) FROM unnest(k_s) k WHERE array_position(names_s, k) IS NULL))
			, type_ids = CASE WHEN tid = ANY(type_ids) THEN type_ids ELSE array_append(type_ids, tid::SMALLINT) END
		WHERE stream_id = sid
		RETURNING names_i, names_a, names_s
		INTO p_i, p_a, p_s;
	END IF;

	-- order property values by the stream property names, without any trailing NULL values;
	-- an instantaneous or accumulating value that is not a number is stored as NULL
	WITH p AS (
		SELECT o, CASE WHEN pg_input_is_valid(jdata_i->>n, 'numeric') THEN (jdata_i->>n)::NUMERIC END AS v
		FROM unnest(p_i) WITH ORDINALITY AS t(n, o)
	)
	SELECT array_agg(v ORDER BY o)
	FROM p
	WHERE o <= (SELECT max(o) FROM p WHERE v IS NOT NULL)
	INTO v_i;

	WITH p AS (
		SELECT o, CASE WHEN pg_input_is_valid(jdata_a->>n, 'numeric') THEN (jdata_a->>n)::NUMERIC END AS v
		FROM unnest(p_a) WITH ORDINALITY AS t(n, o)
	)
	SELECT array_agg(v ORDER BY o)
	FROM p
	WHERE o <= (SELECT max(o) FROM p WHERE v IS NOT NULL)
	INTO v_a;

	WITH p AS (
		SELECT o, jdata_s->n AS v
		FROM unnest(p_s) WITH ORDINALITY AS t(n, o)
	)
	SELECT jsonb_agg(v ORDER BY o)
	FROM p
	WHERE o <= (SELECT max(o) FROM p WHERE v IS NOT NULL)
	INTO v_s;

	INSERT INTO solarhist.dh_datum (stream_id, ts, type_id, data_i, data_a, data_s, data_t)
	VALUES (
		sid
		, ts_crea
		, tid
		, v_i
		, v_a
		, v_s
		, (SELECT array_agg(e) FROM jsonb_array_elements_text(jdata_t) e WHERE e IS NOT NULL)
	)
	ON CONFLICT (stream_id, ts) DO UPDATE
	SET type_id = EXCLUDED.type_id,
		data_i = EXCLUDED.data_i,
		data_a = EXCLUDED.data_a,
		data_s = EXCLUDED.data_s,
		data_t = EXCLUDED.data_t;

	RETURN sid;
END
$$;
